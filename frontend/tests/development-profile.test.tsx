import assert from 'node:assert/strict';
import {afterEach,test} from 'node:test';
import {cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import {PreferencesProvider,preferencesKey} from '../src/context/preferences';
import {ProfessionalDevelopment} from '../src/components/ProfessionalDevelopment';
import {experienceYears,localDate} from '../src/components/ProfessionalDevelopment/utils';
const originalFetch=globalThis.fetch;
afterEach(()=>{cleanup();localStorage.clear();globalThis.fetch=originalFetch;});
test('demo preferences persist, reset their reference date and can be cleared without network calls',async()=>{
 let requests=0;globalThis.fetch=async()=>{requests++;throw new Error('Unexpected request');};
 localStorage.setItem(preferencesKey,JSON.stringify({developmentProfile:{years:5,referenceDate:'2020-01-01',areas:[]}}));
 const view=render(<PreferencesProvider><ProfessionalDevelopment/></PreferencesProvider>);const user=userEvent.setup();
 const slider=screen.getByRole('slider',{name:'Years of professional experience'}) as HTMLInputElement;
 assert.equal(Number(slider.value),experienceYears({years:5,referenceDate:'2020-01-01',areas:[]}));
 fireEvent.change(slider,{target:{value:'8'}});
 await user.click(screen.getByRole('checkbox',{name:'Prioritising findings'}));
 await waitFor(()=>assert.equal(JSON.parse(localStorage.getItem(preferencesKey)??'{}').developmentProfile.years,8));
 assert.equal(JSON.parse(localStorage.getItem(preferencesKey)??'{}').developmentProfile.referenceDate,localDate());
 view.unmount();render(<PreferencesProvider><ProfessionalDevelopment/></PreferencesProvider>);
 assert.equal((screen.getByRole('slider') as HTMLInputElement).value,'8');
 assert((screen.getByRole('checkbox',{name:'Prioritising findings'}) as HTMLInputElement).checked);
 await user.click(screen.getByRole('button',{name:'Clear focus areas'}));
 await user.click(screen.getByRole('button',{name:'Clear experience'}));
 assert(screen.getByText('No development preferences selected. Everything here is optional.'));
 assert.equal(requests,0);
});
test('CV selection replaces and removes local files without reading, storing or transmitting contents',async()=>{
 let requests=0;globalThis.fetch=async()=>{requests++;throw new Error('Unexpected request');};
 const view=render(<PreferencesProvider><ProfessionalDevelopment/></PreferencesProvider>);const user=userEvent.setup();
 assert(screen.getByText('Experimental concept — demo only'));
 const input=screen.getByLabelText(/Upload CV/) as HTMLInputElement;
 const pdf=new window.File(['private-cv-sentinel'],'first.pdf',{type:'application/pdf'});
 await user.upload(input,pdf);
 assert(screen.getByRole('region',{name:'Your development profile'}).textContent?.includes('first.pdf (session only)'));
 await user.upload(input,new window.File(['replacement'],'second.docx',{type:'application/vnd.openxmlformats-officedocument.wordprocessingml.document'}));
 assert.equal(input.files?.[0]?.name,'second.docx');
 assert(!localStorage.getItem(preferencesKey)?.includes('private-cv-sentinel'));
 assert(!localStorage.getItem(preferencesKey)?.includes('second.docx'));
 await user.click(screen.getByRole('button',{name:'Remove CV'}));
 assert.equal(input.files?.length,0);
 await user.upload(input,pdf);
 view.unmount();render(<PreferencesProvider><ProfessionalDevelopment/></PreferencesProvider>);
 assert(screen.getByText('No development preferences selected. Everything here is optional.'));
 assert.equal(requests,0);
 assert(screen.getByText('Concept only — not active'));
 assert(screen.getByText('Future capability — not implemented'));
});
